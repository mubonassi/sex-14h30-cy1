#Estruturas de Condição
#Fazem a verificação de uma condição, e dependendo da resposta, realiza uma ação

#Verificando com String
palavra = input("Digite uma palavra: ")

#Estrutura If
# se (condição for verdadeira):
# {ação}
if palavra == "banana":
    print("Você digitou a palavra banana")

#Verificando com Números   
numero = int(input("Digite um número: "))

if numero == 30:
    print("Você digitou o número 30")
else:
    print("Você NÃO digitou o número 30")

