#Outras formas de repetição com o for

#Você consegue navegar item por item dentro da lista na repetição
lista = ["a","b","c"]
for item in lista:
    print(item)

print("-"*60)

#É possível também fazer a repetição navegar entre cada caractere dentro de uma string
palavra = "paralelepípedo"
for letra in palavra:
    print(letra)
